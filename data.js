/* 上限目安: 表を線形補間し1,000円未満切り捨て。範囲外・目安なしは {error} を返す */
function estimateLimit(incomeMan, familyKey){
  const col = FAMILY_KEYS.indexOf(familyKey) + 1;
  if (col === 0 || !isFinite(incomeMan)) return { error: "invalid" };
  if (incomeMan < 300) return { error: "low" };
  const x = Math.min(incomeMan, 2500);
  const clamped = incomeMan > 2500;
  for (let i = 0; i < LIMIT_TABLE.length - 1; i++){
    const a = LIMIT_TABLE[i], b = LIMIT_TABLE[i+1];
    if (x >= a[0] && x <= b[0]){
      if (a[col] == null || b[col] == null) return { error: "none" };
      const v = a[col]*1000 + (b[col]-a[col])*1000 * (x - a[0]) / (b[0] - a[0]);
      return { value: Math.floor(v/1000)*1000, clamped };
    }
  }
  if (x === 2500){
    const v = LIMIT_TABLE[LIMIT_TABLE.length-1][col];
    return v == null ? { error: "none" } : { value: v*1000, clamped };
  }
  return { error: "invalid" };
}
